#!/usr/bin/env python3
"""Derives the Windows tokens and room strings from the shipped Mac sources. Never edit tokens/tokens_gen.go by hand.
usage: gen_tokens.py [MAC_SOURCES_DIR] > tokens/tokens_gen.go   (default: apps/macos/FirstLine/Sources/FirstLine in this repository)"""
import re, sys, os
sys.stdout.reconfigure(encoding='utf-8', newline='\n')  # same bytes on every OS
# The Mac sources of this repository, at their real paths (apps/windows/scripts -> apps/macos/FirstLine/Sources/FirstLine).
mac = sys.argv[1] if len(sys.argv) > 1 else os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'macos', 'FirstLine', 'Sources', 'FirstLine'))
def rd(p): return open(os.path.join(mac, p), encoding='utf-8').read()
colors, spacing, typo = rd('DesignSystem/Colors.swift'), rd('DesignSystem/Spacing.swift'), rd('DesignSystem/Typography.swift')
room, svc, kept, settings = rd('Session/RoomPresentation.swift'), rd('Session/SessionViewController.swift'), rd('Session/SessionKeptView.swift'), rd('Infrastructure/SettingsStore.swift')
paper = rd('DesignSystem/PaperSheetView.swift')
out = ['// Code generated by scripts/gen_tokens.py from the Mac sources; DO NOT EDIT.', '', 'package tokens', '']
def go_name(s): return s[0].upper() + s[1:]
# colour roles: adaptive(light: 0x.., dark: 0x..) [, lightAlpha: .., darkAlpha: ..]
out.append('// Colour roles, light and dark, 0xRRGGBB with alpha 0..1 (1 when the Mac role is opaque).')
out.append('type Role struct {\n\tLight, Dark           uint32\n\tLightAlpha, DarkAlpha float32\n}\n')
out.append('var (')
for m in re.finditer(r'static var (\w+)NSColor: NSColor \{ adaptive\(light: (0x[0-9A-Fa-f]+), dark: (0x[0-9A-Fa-f]+)(?:, lightAlpha: ([0-9.]+), darkAlpha: ([0-9.]+))?\) \}', colors):
    n, l, d, la, da = m.groups()
    out.append(f'\t{go_name(n)} = Role{{{l.upper().replace("0X","0x")}, {d.upper().replace("0X","0x")}, {la or 1}, {da or 1}}}')
out.append(')\n')
# history ladder
h = re.search(r'dark \? \[([0-9., ]+)\] : \[([0-9., ]+)\]', colors)
out.append(f'// HistoryOpacities is the D-069 ladder, current line first; lines beyond it are gone.')
out.append(f'var HistoryOpacitiesDark = []float32{{{h.group(1)}}}')
out.append(f'var HistoryOpacitiesLight = []float32{{{h.group(2)}}}\n')
# spacing
out.append('// 4-pt spacing and radii.\nconst (')
for m in re.finditer(r'static let (s\d): CGFloat = (\d+)', spacing): out.append(f'\tSpace{m.group(1)[1:]} = {m.group(2)}')
out.append(')\nconst (')
rad = re.search(r'enum FirstLineRadius \{(.*?)\}', spacing, re.S).group(1)
for m in re.finditer(r'static let (\w+): CGFloat = (\d+)', rad): out.append(f'\tRadius{go_name(m.group(1))} = {m.group(2)}')
out.append(')\n')
# session constants
anchor = re.search(r'paperAnchorFraction: CGFloat = ([0-9.]+)', room).group(1)
window = re.search(r'defaultWindow: TimeInterval = ([0-9.]+)', room).group(1)
silence = re.search(r'case strict = (\d+), standard = (\d+), relaxed = (\d+)', settings)
dur = re.search(r'defaultDurationSeconds: TimeInterval = (\d+)', rd('Session/SessionEngine.swift')).group(1)
med = re.search(r'case \.small: (\d+)\s+case \.medium: (\d+)\s+case \.large: (\d+)', settings)
meas = re.search(r'measureCharacters: Int \{ self == \.centered \? (\d+) : (\d+)', settings)
out.append(f'''// Session and room constants.
const (
	AnchorFraction       = {anchor} // the one anchor: writing line and stopped group midpoint (D-070)
	ExitWindowSeconds    = {window}
	DefaultSessionSecond = {dur}
	SilenceStandard      = {silence.group(2)} // seconds until the wipe; the warning starts 3 s earlier
	WarnLeadSeconds      = 3
	WritingSizeMedium    = {med.group(2)} // pt, the Mac default writing size
	MeasureNarrowChars   = {meas.group(1)} // ch (62 narrow column)
	LineHeight           = 1.6
	KeptMeasure          = {re.search(r"static let measure: CGFloat = (\d+)", kept).group(1)}
	KeptVerticalInset    = {re.search(r"static let verticalInset: CGFloat = (\d+)", kept).group(1)}
	FailureReferenceBase = {re.search(r"static let reference: CGFloat = (\d+)", svc).group(1)}
	FailureHeadlineLH    = {re.search(r"failureHeadlineLineHeight: CGFloat = ([0-9.]+)", svc).group(1)}
	FailureNoteLH        = {re.search(r"failureNoteLineHeight: CGFloat = ([0-9.]+)", svc).group(1)}
	PillLabelLift        = {re.search(r"pillLabelLift: CGFloat = ([0-9.]+)", kept).group(1)}
	RoomInset            = {re.search(r"roomInset: CGFloat = (\d+)", svc).group(1)}
	FooterHeight         = {re.search(r"footerHeight: CGFloat = (\d+)", svc).group(1)}
	PaperMargin          = 32 // paper inset from the window (installConstraints)
)
''')
# paper generator constants
out.append(f'''// Paper generator constants (PaperField).
const (
	PaperGrain = {re.search(r"static let grain = ([0-9.]+)", paper).group(1)}
	PaperSize  = {re.search(r"static let size = ([0-9.]+)", paper).group(1)}
	PaperTooth = {re.search(r"static let tooth = ([0-9.]+)", paper).group(1)}
	PaperPulp  = {re.search(r"static let pulp = ([0-9.]+)", paper).group(1)}
)
''')
# strings
def s1(pat, src): return re.search(pat, src).group(1)
strings = {
 'ExitHint': s1(r'exitHintText = "([^"]+)"', svc),
 'Stopped': 'You stopped.',  # failureHeadlineLabel.stringValue
 'DraftDeleted': s1(r'"(Draft deleted\.)"', svc),
 'BeginAgain': s1(r'title: "(Begin again)"', svc),
 'Warning': s1(r'"(KEEP TYPING OR THE DRAFT IS DELETED\.)"', svc),
 'TypeToStart': s1(r'"(Type to start)"', svc),
 'ExitLink': s1(r'title: "(ESC - EXIT)"', svc),
 'KeptHeading': s1(r'labelWithString: "(You wrote it down\.)"', kept),
 'CopyText': s1(r'title: "(COPY TEXT)"', kept),
 'RunAgain': s1(r'title: "(RUN IT AGAIN)"', kept),
 'Copied': s1(r'"(COPIED)"', svc),
 'CopyRetry': s1(r'"(TRY COPY AGAIN)"', svc),
 'CountRule': s1(r'countRule = "([^"]+)"', room),
 'AnnounceDanger': s1(r'announce\("(Keep typing or the draft is deleted\. Three seconds left\.)"\)', svc),
 'AnnounceKept': s1(r'announce\("(You wrote it down\. Nothing here is saved\. Copy it before you leave\.)"\)', svc),
 'AnnounceBlocked': s1(r'announce\("(Blocked\. Forward only\.)"\)', svc),
 'AnnounceTrialSpent': s1(r'case \.trialSpent:\s*return "\\\(deleted\) (Three free sessions used\. A license is needed to keep writing\.)"', room),
 'AnnounceLicenseNeeded': s1(r'case \.licenseNeeded:\s*return "\\\(deleted\) (A license is needed to keep writing\.)"', room),
}
out.append('// Room strings, verbatim from the Mac room.\nconst (')
for k, v in strings.items(): out.append(f'\tStr{k} = {v!r}'.replace("'", '"'))
out.append(')\n')

# ---------------------------------------------------------------------------------------------------------------
# The product around the room (home, rules, activation, settings, licence service configuration).
# Every Mac literal is *searched for verbatim* before it is emitted: when the Mac copy changes, this script fails
# loudly instead of drifting. WIN_SUBS turns Mac wording into Windows wording; WIN_OVERRIDES replaces a string whose
# meaning differs on Windows (each with its reason, mirrored in SYNC.md).
import plistlib
plist = plistlib.loads(open(os.path.join(mac, 'Info.plist'), 'rb').read())
state, home, upgrade, settingsvc = rd('App/AppState.swift'), rd('App/HomeViewController.swift'), rd('Upgrade/UpgradeViewController.swift'), rd('Settings/SettingsViewController.swift')
rules, models, engine = rd('App/RulesViewController.swift'), rd('Licensing/LicenseModels.swift'), rd('Session/SessionEngine.swift')
checkout = rd('Licensing/CheckoutClient.swift')
WIN_SUBS = [('On the Mac: ', ''), ('2-Mac', '2-PC'), ('2 Macs', '2 PCs'), ('this Mac', 'this PC'), ('Waffo order number', 'order number'), ('This Mac', 'This PC')]
WIN_OVERRIDES = {
    # the licence lives in the Windows Credential Manager, not a file on disk (no "disk permissions" to check)
    'storageFailure': ('Could not save the license on this Mac. Check disk permissions and try again.',
                       'Could not save the license on this PC. Check access to the Windows Credential Manager and try again.'),
}
def win(s):
    for a, b in WIN_SUBS: s = s.replace(a, b)
    assert 'Mac' not in s, 'Mac wording left in a Windows string: ' + s
    return s
def lit(src, text, name):
    """The Mac literal must exist verbatim; returns the Windows wording."""
    if '"' + text + '"' not in src and text not in src: raise SystemExit(f'Mac string for {name} changed or moved: {text!r}')
    return win(text)
def q(s): return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'
P = []
def const(name, val): P.append(f'\t{name} = {q(val)}')
def num(name, val): P.append(f'\t{name} = {val}')
# licence service configuration: Info.plist is the one source (the same keys the Mac release script checks)
const('LicenseServiceURL', plist['WIDLicenseServiceURL']); const('LicenseProductID', plist['WIDLicenseProductID'])
const('LicensePublicKey', plist['WIDLicensePublicKey']); const('CheckoutFallbackURL', plist['WIDCheckoutURL'])
const('DisplayPrice', plist['WIDDisplayPrice'])
const('WebTrialURL', s1(r'webTrialURL = URL\(string: "([^"]+)"\)', state)); const('SupportURL', s1(r'let url = URL\(string: "(https://writeitdown\.app/support\.html)"\)', state))
num('TrialSessionLimit', s1(r'static let trialSessionLimit = (\d+)', settings))
num('LicenseOfflineGraceSeconds', 7 * 24 * 60 * 60) if 'licenseOfflineGraceInterval: TimeInterval = 7 * 24 * 60 * 60' in state else sys.exit('grace changed')
num('LicenseTokenLifetimeSeconds', 7 * 24 * 60 * 60) if 'static let lifetime: Int64 = 7 * 24 * 60 * 60' in rd('Licensing/LicenseTokenVerifier.swift') else sys.exit('lifetime changed')
assert 'url.scheme == "https", url.host != nil' in state.replace('\n', ' ') or 'scheme == "https"' in state
# home
const('HomeTitle', lit(home, 'How long?', 'HomeTitle')); const('HomeMinutes', lit(home, 'Minutes', 'HomeMinutes'))
const('HomeSilence', lit(home, 'Delete after silence', 'HomeSilence')); const('HomeBegin', lit(home, 'Begin', 'HomeBegin'))
const('HomeRulesHelp', lit(home, 'How it works', 'HomeRulesHelp'))
const('HomeLockupLabel', 'Write It Down')
ch = re.search(r'durationChoices: \[TimeInterval\] = \[([0-9, ]+)\]', engine).group(1)
P.append(f'\tDurationChoices = []int{{{ch}}}'.replace('var ', ''))
sl = re.search(r'case strict = (\d+), standard = (\d+), relaxed = (\d+)', settings)
labels = re.findall(r'case \.(\w+): "([^"]+)"', re.search(r'enum SilenceLimit.*?\n\}\n', settings, re.S).group(0))
P.append('\tSilenceChoices = []int{%s, %s, %s}' % sl.groups())
P.append('\tSilenceLabels = []string{%s}' % ', '.join(q(l) for _, l in labels))
# rules sheet
const('RulesEyebrow', lit(rules, 'How it works', 'RulesEyebrow')); const('RulesHeading', lit(rules, 'Forward only. Nothing kept.', 'RulesHeading'))
const('RulesSub', lit(rules, 'Open it, start typing, say the thing you have been avoiding. The only way out is through.', 'RulesSub'))
rl = re.findall(r'rule\("([^"]+)",\s*"([^"]+)"\)', rules)
assert len(rl) == 3
for i, (t, b) in enumerate(rl, 1): const(f'Rule{i}Title', win(t)); const(f'Rule{i}Body', win(b))
const('RulesDone', lit(rules, 'Done', 'RulesDone'))
# activation (upgrade) card
const('UpgradeTitle', lit(upgrade, 'Activate Write It Down', 'UpgradeTitle')); const('UpgradeTitleLicensed', 'Write It Down')
const('UpgradeSubtitle', lit(upgrade, 'A license is required to keep writing on this Mac.', 'UpgradeSubtitle'))
const('UpgradeSubtitleLicensed', lit(upgrade, 'This Mac is licensed.', 'UpgradeSubtitleLicensed'))
const('UpgradeFieldLabel', lit(upgrade, 'Order number or activation code', 'UpgradeFieldLabel'))
const('UpgradePlaceholder', lit(upgrade, 'WID-XXXX-XXXX', 'UpgradePlaceholder'))
const('UpgradeActivate', lit(upgrade, 'Activate', 'UpgradeActivate')); const('UpgradeActivating', lit(upgrade, 'Activating', 'UpgradeActivating'))
const('UpgradeStartWriting', lit(upgrade, 'Start writing', 'UpgradeStartWriting'))
const('UpgradeEnterFirst', lit(upgrade, 'Enter your order number or activation code first.', 'UpgradeEnterFirst'))
const('UpgradePricing', lit(upgrade, 'One payment. 2 Macs. 14-day refund.', 'UpgradePricing'))
const('UpgradeCheckoutUnavailable', lit(upgrade, 'Checkout is not available yet.', 'UpgradeCheckoutUnavailable'))
const('UpgradeWebTrial', lit(upgrade, 'Try the free web room', 'UpgradeWebTrial'))
const('UpgradeBuyFormat', lit(upgrade, 'Buy a license, \\(AppState.displayPrice) once', 'UpgradeBuyFormat').replace('\\(AppState.displayPrice)', '%s'))
const('UpgradeOpeningCheckout', lit(upgrade, 'Opening checkout...', 'UpgradeOpeningCheckout'))
const('UpgradeCleanupActive', 'License active on this PC.') if 'License active on this Mac.' in upgrade else sys.exit('cleanup copy changed')
# licence and access status (AppState), activation errors (LicenseModels)
for k, t in [('StatusChecking', 'Checking license...'), ('StatusNotActivated', 'License not activated on this Mac. Enter your order number or activation code.'),
             ('StatusNeedsValidation', 'License needs online validation. Reopen the app when connected.'), ('StatusWrongProduct', 'License does not match the configured writeitdown product.'),
             ('StatusActive', 'License active.'), ('StatusRevoked', 'License revoked. Enter a valid order number or activation code.'),
             ('StatusInvalid', 'License invalid. Activate this Mac again.'), ('StatusUnknown', 'License status unknown. Reconnect to validate.'),
             ('StatusInactive', 'Activate this Mac to start writing.'),
             ('TrialReadError', "Could not read trial usage. Check access to the app's settings and reopen the app."),
             ('TrialSaveError', "Could not save trial usage. Check access to the app's settings and reopen the app.")]:
    const(k, lit(state, t, k))
assert 'Free trial: \\(trialSessionsRemaining) of \\(Self.trialSessionLimit) sessions left, "' in state and '"counted at the first character."' in state
const('TrialLeftFormat', 'Free trial: %d of %d sessions left, counted at the first character.')
for m in re.finditer(r'case \.(\w+)(?:\(let statusCode\))?:\s*return "([^"]*)"', models):
    name, text = m.groups()
    text = text.replace('\\(statusCode)', '%d')
    if name in WIN_OVERRIDES:
        assert WIN_OVERRIDES[name][0] == text, f'Mac {name} changed'
        text = WIN_OVERRIDES[name][1]
    else: text = win(text)
    const('Err' + go_name(name), text)
assert len(re.findall(r'case \.(\w+)(?:\(let statusCode\))?:\s*return "', models)) == 10
# settings
const('SettingsTitle', lit(settingsvc, 'Settings', 'SettingsTitle')); const('SettingsDone', lit(settingsvc, 'Done', 'SettingsDone'))
const('SettingsLicense', lit(settingsvc, 'License', 'SettingsLicense')); const('SettingsAbout', lit(settingsvc, 'About', 'SettingsAbout'))
const('SettingsExplanation', lit(settingsvc, 'Enter your order number or activation code to activate this Mac.', 'SettingsExplanation'))
const('SettingsFieldPlaceholder', lit(settingsvc, 'Order number or activation code', 'SettingsFieldPlaceholder'))
const('SettingsActivated', 'Activated %s') if '"Activated \\(formatted($0))"' in settingsvc else sys.exit('settings copy changed')
const('SettingsLastValidated', 'Last validated %s') if '"Last validated \\(formatted($0))"' in settingsvc else sys.exit('settings copy changed')
const('SettingsVersionFormat', 'Version %s') if '"Version \\(version)"' in settingsvc else sys.exit('settings copy changed')
out.append('// The product around the room: licence service configuration (Info.plist), home, rules, activation, settings.\n// Mac wording becomes Windows wording through scripts/gen_tokens.py (WIN_SUBS, WIN_OVERRIDES); see SYNC.md.\nconst (')
out += [l for l in P if 'Choices' not in l and 'Labels' not in l]
out.append(')\n')
out.append('var (')
out += [l for l in P if 'Choices' in l or 'Labels' in l]
out.append(')\n')
print('\n'.join(out))
